# How every exercise model paints the three heads of the pectoralis major
# (2026-10-22): the clavicular (upper), sternal (middle) and abdominal (lower)
# meshes, read off each mesh's bound material with the tiers.py rule (level =
# the larger of the red diffuse and the emissive red / 0.153; grey is unlit;
# bright >= 0.6 is primary, anything lit below that is secondary). The chest-
# series rigs bind the heads to FF_Highlight_UpperChest / MidChest / LowerChest,
# the others bind all three to one Chest material, so they come out equal.
# Writes GymWorkout/Models/ChestPaint.swift, which the muscle map reads to light
# the chest's three bands the way the exercise's own model does.
#   python3.13 chest_paint.py        (Blender's Python: pxr)
import os, re, glob
REPO = "/Users/sammanhcuong/Developer/GymWorkout"
os.environ.setdefault("PXR_AR_DEFAULT_SEARCH_PATH", REPO + "/GymWorkout/Resources/Models/Shared")
from pxr import Usd, UsdShade

HEADS = ("Clavicular", "Sternal", "Abdominal")


def level(mesh):
    mat, _ = UsdShade.MaterialBindingAPI(mesh).ComputeBoundMaterial()
    if not mat:
        return 0.0
    src = mat.ComputeSurfaceSource()[0]
    if not src:
        return 0.0
    a, e = src.GetInput("diffuseColor"), src.GetInput("emissiveColor")
    c = a.Get() if a else None
    g = e.Get() if e else None
    r = 0.0
    if c is not None and not (abs(c[0] - c[1]) < 0.05 and abs(c[1] - c[2]) < 0.05):
        r = c[0]
    if g is not None and g[0] > 0.01 and g[0] > 2 * g[2]:
        r = max(r, min(1.0, g[0] / 0.153))
    return r


def rank(r):
    return None if r < 0.05 else ".primary" if r >= 0.6 else ".secondary"


rows = {}
for path in sorted(glob.glob(REPO + "/GymWorkout/Resources/Models/*/*.usdc")):
    group, res = path.split("/")[-2], os.path.basename(path)[:-5]
    if group == "Shared" or res.startswith("XRay"):
        continue
    st = Usd.Stage.Open(path)
    best = dict.fromkeys(HEADS, 0.0)
    for p in st.Traverse():
        if p.GetTypeName() != "Mesh":
            continue
        m = re.match(r"PectoralisMajor_(Clavicular|Sternal|Abdominal)_[LR]_Mesh", p.GetName())
        if m:
            best[m[1]] = max(best[m[1]], level(p))
    ranks = [rank(best[h]) for h in HEADS]
    if any(ranks):
        rows[res] = ranks

lines = []
for res, (u, m, l) in sorted(rows.items()):
    lines.append(f'        "{res}": .init(upper: {u or "nil"}, middle: {m or "nil"}, lower: {l or "nil"}),')
swift = """//
//  ChestPaint.swift
//  GymWorkout
//
//  GENERATED by Tools/body-map/chest_paint.py — do not edit by hand.
//
//  How each exercise model paints the three heads of the pectoralis major:
//  the clavicular (upper), sternal (middle) and abdominal (lower) chest,
//  bright = primary, dim or faint = secondary, missing = unlit. Models whose
//  chest is unlit are left out. The muscle map lights its three chest bands
//  from this, so they match the model the user trains with.
//

enum ChestPaint {
    /// Codable so a logged exercise can keep the paint it was trained with.
    struct Heads: Hashable, Codable {
        let upper: ActivationRank?
        let middle: ActivationRank?
        let lower: ActivationRank?
    }

    /// The heads as the model `resource` paints them, or nil when its chest
    /// is unlit or the model is unknown.
    static func heads(forModel resource: String) -> Heads? { table[resource] }

    /// The heads of the exercise's own model (a stance picker's default). For
    /// a model that paints no chest, the heads its chest rows name: "Upper
    /// Pectoralis" the upper head alone, "Pectoralis Major" all three.
    static func heads(forExerciseNamed name: String) -> Heads? {
        if let painted = SampleData.modelName(forExerciseNamed: name).flatMap({ heads(forModel: $0) }) {
            return painted
        }
        guard let exercise = ExerciseCatalog.exercise(named: name),
              let content = SampleData.content(for: exercise) else { return nil }
        return heads(fromRows: content.activation)
    }

    /// The heads the chest rows name, each at its strongest row's rank, the
    /// way the map lights them; nil when no row names the chest.
    static func heads(fromRows rows: [MuscleActivation]) -> Heads? {
        var ranks: [ActivationRank?] = [nil, nil, nil]
        for row in rows {
            for (region, _) in BodyRegion.regions(forMuscle: row.name) {
                guard let i = BodyRegion.chestHeads.firstIndex(of: region), ranks[i] != .primary else { continue }
                ranks[i] = row.rank
            }
        }
        if ranks.allSatisfy({ $0 == nil }) { return nil }
        return Heads(upper: ranks[0], middle: ranks[1], lower: ranks[2])
    }

    private static let table: [String: Heads] = [
ROWS
    ]
}
""".replace("ROWS", "\n".join(lines))
open(REPO + "/GymWorkout/Models/ChestPaint.swift", "w").write(swift)
print(len(rows), "models with a lit chest")
