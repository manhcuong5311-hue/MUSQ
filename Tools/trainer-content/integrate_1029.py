# Integrates the 2026-10-29 model-only batch (integrate_1012.py adapted)
# into the app: setup steps into setup.py, trainer content (gen.py) and the
# content-map entries into SampleData.swift (the library rows and the model
# map went in with the models), and any family fault ghosts into
# FaultPoses.swift. Everything it writes sits between its own begin/end
# markers, which a re-run replaces, so it can run again after any family
# edit, and families that are not written yet are simply absent.
#   python3 integrate_1029.py <scratch dir> [--only <family>]... [--skip <family>]...
import json, os, re, sys, glob
HERE = os.path.dirname(os.path.abspath(__file__)); os.chdir(HERE); sys.path.insert(0, HERE)
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SD = os.path.join(REPO, "GymWorkout/Models/SampleData.swift")
FP = os.path.join(REPO, "GymWorkout/Models/FaultPoses.swift")
SU = os.path.join(HERE, "setup.py")
TAG = "Model-only exercises (2026-10-29)"


def put(text, begin, end, body, anchor_before):
    """Replace what sits between begin and end, or insert the block before
    `anchor_before` the first time."""
    if begin in text:
        a = text.index(begin) + len(begin); b = text.index(end, a)
        return text[:a] + body + text[b:]
    assert text.count(anchor_before) == 1, anchor_before[:60]
    return text.replace(anchor_before, begin + body + end + anchor_before)


import spec_1029 as S
from common_1_50 import SETUP as NEW
ONLY = [sys.argv[k + 1] for k, a in enumerate(sys.argv) if a == "--only"]
SKIP = [sys.argv[k + 1] for k, a in enumerate(sys.argv) if a == "--skip"]
if ONLY:
    SKIP += [f for f in S.FAMILIES if f not in ONLY]
for fam in SKIP:
    S.SPEC[:] = [e for e in S.SPEC if e["name"] not in S.FAMILIES[fam]]
# Families with no spec module yet are simply not in SPEC.
written = [e["name"] for e in S.SPEC]
order = [n for n in S.ORDER if n in written]
problems = S.validate(order) + S.validate_library(order)
assert not problems, problems

# 1. setup.py
s = open(SU).read()
body = "".join(f'    "{n}": [\n' + "".join(f'        "{t}",\n' for t in NEW[n]) + "    ],\n" for n in order)
s = put(s, f"    # BEGIN {TAG}\n", f"    # END {TAG}\n", body, s[s.rstrip().rindex("}"):])
open(SU, "w").write(s)

# 2. gen
import importlib, setup  # noqa: E402
importlib.reload(setup)
sys.modules["spec"] = S
import gen  # noqa: E402
swift = "\n\n".join(gen.emit(e) for e in S.SPEC)
json.dump({"ex1029": swift}, open("generated_1029.json", "w"))
lines = []
for e in S.SPEC:
    lines.append(e["name"])
    for (cue, label, joint), (x, y, side, jx, jy) in gen.layout(e["name"], e["annotations"], e.get("overrides"), e.get("slots")):
        lines.append(f"   {label:30s} {side:8s} x={x:.3f} y={y:.2f}  joint {joint:22s} at ({jx:.2f},{jy:.2f})")
os.makedirs(sys.argv[1], exist_ok=True)
open(os.path.join(sys.argv[1], "layout_1029.txt"), "w").write("\n".join(lines) + "\n")

# 3. SampleData.swift: content map entries and content block.
t = open(SD).read()
entries = "".join(f'        "{e["name"]}": {e["var"]}Content,\n' for e in S.SPEC)
anchor = "        // END Desktop 300-400 (2026-10-12)\n    ]\n\n    static func content(for"
if f"        // BEGIN {TAG}\n" not in t:
    assert t.count(anchor) == 1
    t = t.replace(anchor, anchor.replace("    ]\n", f"        // BEGIN {TAG}\n        // END {TAG}\n    ]\n", 1))
t = put(t, f"        // BEGIN {TAG}\n", f"        // END {TAG}\n", entries, "")
header = f'''
    // MARK: - {TAG}
    //
    // The exercises that shipped with a model but no coaching, so the
    // trainer gated them as MODEL ONLY: the Olympic lifts, jumps and
    // conditioning work of the 401-500 swap, three cable arm lifts, three
    // glute machines, two more legs, two core lifts and the three female
    // lifts. Generated by `Tools/trainer-content/gen.py` from
    // `spec_1029.py`; each family file's header lists what its models show
    // and its sources, and `notes_1029_<family>.md` maps the copy's claims
    // to them.

'''
if f"    // BEGIN {TAG} content\n" not in t:
    assert t.rstrip().endswith("}")
    t = t.rstrip()[:-1].rstrip() + "\n" + f"    // BEGIN {TAG} content\n    // END {TAG} content\n" + "}\n"
t = put(t, f"    // BEGIN {TAG} content\n", f"    // END {TAG} content\n", (header + swift + "\n") if S.SPEC else "", "")
open(SD, "w").write(t)

# 4. FaultPoses.swift, only for families that have ghost files.
paths = sorted(glob.glob(os.path.join(REPO, "Tools/fault-review/faults_1029_*.swift.txt")))
pieces, table = [], []
for path in paths:
    fam = re.search(r"faults_1029_(\w+)\.swift\.txt$", path).group(1)
    if fam in SKIP: continue
    x = open(path).read(); a, b = x.index("// MARK: PIECES"), x.index("// MARK: TABLE")
    pieces.append(x[a + 15:b].strip("\n")); table.append(x[b + 14:].strip("\n"))
if pieces:
    f = open(FP).read()
    f = put(f, f"    // BEGIN {TAG} pieces\n", f"    // END {TAG} pieces\n",
            "\n".join(pieces) + "\n", "    // MARK: Exercises 1-50 redo pieces (2026-09-29)\n")
    f = put(f, f"        // BEGIN {TAG}\n", f"        // END {TAG}\n",
            "\n".join(table) + "\n", "        // MARK: Exercises 1-50 redo (2026-09-29)\n")
    open(FP, "w").write(f)
print(f"integrated {len(S.SPEC)} exercise(s), {len(pieces)} fault family(ies); layout in {sys.argv[1]}/layout_1029.txt")
